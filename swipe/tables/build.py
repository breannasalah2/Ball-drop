#!/usr/bin/env python3
"""Embed schema.sql into the swipe-tables edge function.

Run from anywhere:  python3 swipe/tables/build.py
Then deploy supabase/functions/swipe-tables (index.ts, schema_sql.ts).
"""
import pathlib

here = pathlib.Path(__file__).resolve().parent
fn = here / "supabase" / "functions" / "swipe-tables"
sql = "\n".join(l for l in (here / "schema.sql").read_text(encoding="utf-8").splitlines() if not l.lstrip().startswith("--"))

def ts_const(name, text):
    # String.raw keeps the text byte-for-byte, so the deployed file stays readable.
    if "`" in text or "${" in text:
        raise SystemExit("%s holds a backtick or ${, which String.raw can't carry" % name)
    return "// Generated by swipe/tables/build.py. Do not edit by hand.\nexport const %s = String.raw`%s`;\n" % (name, text)

(fn / "schema_sql.ts").write_text(ts_const("SCHEMA_SQL", sql.strip()), encoding="utf-8")
print("wrote", fn / "schema_sql.ts")
